  /// Minimum experience needed to reach [level] for a Gen II [speciesId].
  static int forLevel(int speciesId, int level) {
    if (speciesId < 1 || speciesId > 251) {
      throw RangeError.range(speciesId, 1, 251, 'speciesId');
    }
    if (level < 1 || level > 100) {
      throw RangeError.range(level, 1, 100, 'level');
    }

    final n = level;
    final cube = n * n * n;
    if (_slow.contains(speciesId)) return (5 * cube) ~/ 4;
    if (_mediumFast.contains(speciesId)) return cube;
    if (_fast.contains(speciesId)) return (4 * cube) ~/ 5;
    if (_mediumSlow.contains(speciesId)) {
      // The original game underflows at level 1 for this curve. A save editor
      // uses the sensible minimum (zero experience) for that edge case.
      return ((6 * cube) ~/ 5 - 15 * n * n + 100 * n - 140)
          .clamp(0, 0xffffff)
          .toInt();
    }
    throw FormatException('No hay curva de experiencia para $speciesId.');
  }
