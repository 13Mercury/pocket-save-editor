bool? crystalCanLearnMove(int speciesId, int moveId) {
  if (moveId == 0) return true;
  var hasKnownLearnset = false;
  for (final lineSpeciesId in crystalEvolutionLine(speciesId)) {
    final learnset = crystalLearnableMoves[lineSpeciesId];
    if (learnset == null) continue;
    hasKnownLearnset = true;
    if (learnset.contains(moveId)) return true;
  }
  return hasKnownLearnset ? false : null;
}

class CrystalMovePickerGroup {
  final String label;
  final List<int> moveIds;
  final Map<int, int> levels;
  final Map<int, int> learnedBySpecies;

  const CrystalMovePickerGroup(
    this.label,
    this.moveIds, {
    this.levels = const {},
    this.learnedBySpecies = const {},
  });
}

List<CrystalMovePickerGroup> crystalMovePickerGroups(int speciesId) {
  final levelMoves = <int, int>{};
  final learnedBySpecies = <int, int>{};
  for (final sourceId in crystalEvolutionLine(speciesId)) {
    for (final entry in crystalLevelUpMoveLevels(sourceId).entries) {
      if (!crystalMoves.containsKey(entry.key) ||
          levelMoves.containsKey(entry.key)) {
        continue;
      }
      levelMoves[entry.key] = entry.value;
      learnedBySpecies[entry.key] = sourceId;
    }
  }
  final levelIds = levelMoves.keys.where(crystalMoves.containsKey).toList()
    ..sort((a, b) {
      final byLevel = levelMoves[a]!.compareTo(levelMoves[b]!);
      if (byLevel != 0) return byLevel;
      return crystalMoves[a]!.name.toLowerCase().compareTo(
        crystalMoves[b]!.name.toLowerCase(),
      );
    });
  final otherLearnable = <int>[];
  final unavailable = <int>[];
  for (final id in crystalMoves.keys) {
    if (levelMoves.containsKey(id)) continue;
    if (crystalCanLearnMove(speciesId, id) == true) {
      otherLearnable.add(id);
    } else {
      unavailable.add(id);
    }
  }
  int byName(int a, int b) => crystalMoves[a]!.name.toLowerCase().compareTo(
    crystalMoves[b]!.name.toLowerCase(),
  );
  otherLearnable.sort(byName);
  unavailable.sort(byName);
  return [
    if (levelIds.isNotEmpty)
      CrystalMovePickerGroup(
        'Por nivel',
        List.unmodifiable(levelIds),
        levels: levelMoves,
        learnedBySpecies: learnedBySpecies,
      ),
    if (otherLearnable.isNotEmpty)
      CrystalMovePickerGroup(
        'Otros métodos',
        List.unmodifiable(otherLearnable),
      ),
    if (unavailable.isNotEmpty)
      CrystalMovePickerGroup(
        'No compatible en Cristal',
        List.unmodifiable(unavailable),
      ),
  ];
}
