List<int> crystalEvolutionLine(int speciesId) {
  final line = <int>[speciesId];
  var current = speciesId;
  while (crystalEvolutionParents.containsKey(current)) {
    current = crystalEvolutionParents[current]!;
    line.add(current);
  }
  return List.unmodifiable(line);
}

String crystalMoveLevelDescription({
  required int speciesId,
  required int level,
  required int learnedBySpeciesId,
}) {
  final canHatchAsSpecies =
      !crystalEvolutionParents.containsKey(learnedBySpeciesId) &&
      !_crystalNonHatchableSpecies.contains(learnedBySpeciesId);
  final timing = level == 1 && canHatchAsSpecies
      ? 'Nivel 1 · al nacer'
      : 'Nivel $level';
  return learnedBySpeciesId == speciesId
      ? timing
      : '${PokemonSpecies.getName(learnedBySpeciesId)} · $timing';
}

